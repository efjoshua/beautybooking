/**
 * Generates db/migrations/0003_history.sql — a realistic trading history.
 *
 * WHY THIS EXISTS
 * The prototype's PBS.revenue held hand-written headline figures (3,145,000 for
 * August) that were never derived from its own appointment list — that list only
 * sums to a fraction of it. Now that reports are real SQL over real rows, those
 * two things must agree, and the honest way to make them agree is to have the
 * rows actually exist.
 *
 * So this seeds ~10 weeks of trading (1 Jun – 7 Aug 2026) that respects:
 *   - each stylist's rota and the salon's opening hours
 *   - who is qualified for which service category
 *   - no double-booking of a stylist
 *   - realistic weekday/weekend demand, payment mix and cancellation rate
 *
 * Output is deterministic (seeded PRNG), so regenerating gives the same data
 * and migrations stay reproducible.
 *
 *   node _dev/gen-history.js && php db/migrate.php
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
global.window = {};
require(path.join(ROOT, '_dev/seed-data.js'));
const PBS = global.window.PBS;

/* ---- deterministic PRNG (mulberry32) so output never drifts ------------- */
let _s = 0x9E3779B9;
function rnd() {
  _s |= 0; _s = (_s + 0x6D2B79F5) | 0;
  let t = Math.imul(_s ^ (_s >>> 15), 1 | _s);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const pick = arr => arr[Math.floor(rnd() * arr.length)];
const chance = p => rnd() < p;
const weighted = pairs => {                    // [[value, weight], …]
  const total = pairs.reduce((t, p) => t + p[1], 0);
  let r = rnd() * total;
  for (const [v, w] of pairs) { if ((r -= w) <= 0) return v; }
  return pairs[pairs.length - 1][0];
};

/* ---- SQL helpers -------------------------------------------------------- */
const q = v => v === null || v === undefined ? 'NULL'
  : typeof v === 'number' ? String(v)
  : "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";
const staffId  = ref => `(SELECT id FROM staff WHERE ref = ${q(ref)})`;
const svcId    = ref => `(SELECT id FROM services WHERE ref = ${q(ref)})`;
const clientId = ref => `(SELECT id FROM clients WHERE ref = ${q(ref)})`;
const apptId   = ref => `(SELECT id FROM appointments WHERE ref = ${q(ref)})`;

const addMin = (hhmm, mins) => {
  const [h, m] = hhmm.split(':').map(Number);
  const t = h * 60 + m + mins;
  return String(Math.floor(t / 60)).padStart(2, '0') + ':' + String(t % 60).padStart(2, '0');
};
const toMin = hhmm => { const [h, m] = hhmm.split(':').map(Number); return h * 60 + m; };
const iso = d => d.toISOString().slice(0, 10);

/* ---- the salon's actual constraints ------------------------------------ */
const ROTA = {                                   // 0 = Monday … 6 = Sunday
  'ST-01': [1, 1, 1, 1, 1, 1, 0], 'ST-02': [1, 1, 1, 1, 1, 1, 0],
  'ST-03': [0, 1, 1, 1, 1, 1, 1], 'ST-04': [1, 1, 1, 1, 1, 0, 0],
  'ST-05': [0, 0, 1, 1, 1, 1, 1], 'ST-06': [1, 1, 1, 1, 1, 1, 0],
};
const HOURS = PBS.salon.hours.map(h => ({ open: h.open, close: h.close, closed: h.closed }));
/* Saturday is the busy day; Sunday and Monday are quiet. */
const DEMAND = [0.62, 0.70, 0.78, 0.88, 0.95, 1.00, 0.42];
const PAY_MIX = [['momo', 43], ['cash', 30], ['om', 19], ['card', 8]];

const staffFor = catSlug => PBS.staff.filter(s => s.cats.includes(catSlug)).map(s => s.id);
const servicesByCat = {};
PBS.categories.forEach(c => { servicesByCat[c.id] = PBS.services.filter(s => s.cat === c.id); });
/* Demand per category, loosely matching the prototype's revenue split. */
const CAT_MIX = [['braids', 26], ['hair', 28], ['nails', 27], ['facials', 12], ['massage', 7]];

const out = [];
const S = s => out.push(s);
S('-- =============================================================================');
S('-- Princess Beauty Salon — trading history (1 Jun – 7 Aug 2026)');
S('-- GENERATED by _dev/gen-history.js. Deterministic; safe to regenerate.');
S('-- Exists so revenue reports are computed from real rows rather than from');
S('-- hand-written headline figures. See the header of that script.');
S('-- =============================================================================');
S('');
S('SET NAMES utf8mb4;');
S('');

const clientRefs = PBS.clients.map(c => c.id);
let apptNo = 0, itemLines = [], stockNo = 0, stockLines = [];
const startDate = new Date('2026-06-01T00:00:00Z');
const endDate   = new Date('2026-08-07T00:00:00Z');

let totalAppts = 0, totalRevenue = 0;

for (let d = new Date(startDate); d <= endDate; d.setUTCDate(d.getUTCDate() + 1)) {
  const date = iso(d);
  const wd = (d.getUTCDay() + 6) % 7;              // 0 = Monday
  const hours = HOURS[wd];
  if (hours.closed) continue;

  /* who is on shift, and when each of them is next free */
  const freeAt = {};
  PBS.staff.forEach(s => { if (ROTA[s.id][wd]) freeAt[s.id] = toMin(hours.open); });

  /* 5–11 bookings a day, scaled by weekday demand */
  const target = Math.round((5 + rnd() * 6) * DEMAND[wd]);

  for (let i = 0; i < target; i++) {
    const cat = weighted(CAT_MIX);
    const eligible = staffFor(cat).filter(id => id in freeAt);
    if (!eligible.length) continue;

    /* prefer whoever is free earliest — mirrors how a salon actually fills up */
    eligible.sort((a, b) => freeAt[a] - freeAt[b]);
    const stf = eligible[0];

    const svc = weighted(servicesByCat[cat].map(s => [s, s.popular ? 3 : 1]));
    const startM = Math.max(freeAt[stf], toMin(hours.open));
    if (startM + svc.duration > toMin(hours.close)) continue;   // would run past closing

    const start = String(Math.floor(startM / 60)).padStart(2, '0') + ':' + String(startM % 60).padStart(2, '0');
    const end = addMin(start, svc.duration);
    freeAt[stf] = startM + svc.duration + 10;        // 10-minute turnaround

    /* past bookings are mostly completed; a few fall over */
    const status = weighted([['completed', 90], ['cancelled', 6], ['no-show', 4]]);
    const done = status === 'completed';
    const pay = done ? weighted(PAY_MIX) : 'unpaid';
    const addons = done && chance(0.22) ? [1000, 1500, 2000, 2500, 3000][Math.floor(rnd() * 5)] : 0;
    const tip = done && chance(0.30) ? [500, 1000, 1500, 2000][Math.floor(rnd() * 4)] : 0;
    const grand = svc.price + addons + tip;

    const ref = 'AP-' + String(++apptNo).padStart(4, '0');
    const client = pick(clientRefs);

    S(`INSERT INTO appointments (ref, client_id, staff_id, booked_on, starts_at, ends_at, duration_minutes, status, payment_method, paid_at, services_total, addons_total, tip_total, grand_total, source) VALUES ` +
      `(${q(ref)}, ${clientId(client)}, ${staffId(stf)}, ${q(date)}, ${q(start + ':00')}, ${q(end + ':00')}, ` +
      `${svc.duration}, ${q(status)}, ${q(pay)}, ${done ? q(date + ' ' + end + ':00') : 'NULL'}, ` +
      `${svc.price}, ${addons}, ${tip}, ${grand}, ${q(weighted([['online', 55], ['walk-in', 25], ['phone', 15], ['admin', 5]]))});`);
    itemLines.push(
      `INSERT INTO appointment_items (appointment_id, service_id, service_name, unit_price, duration_minutes, qty, line_total) VALUES ` +
      `(${apptId(ref)}, ${svcId(svc.id)}, ${q(svc.name)}, ${svc.price}, ${svc.duration}, 1, ${svc.price});`);

    /* completing a service consumes its linked stock */
    if (done) {
      (svc.uses || []).forEach(p => {
        const sref = 'SH-' + String(++stockNo).padStart(4, '0');
        stockLines.push(
          `INSERT INTO stock_movements (ref, product_id, movement_type, qty, reference, note, staff_id, moved_on) VALUES ` +
          `(${q(sref)}, (SELECT id FROM products WHERE ref = ${q(p)}), 'out', -1, ${q(ref)}, ` +
          `${q('Used in ' + svc.name)}, ${staffId(stf)}, ${q(date)});`);
      });
      totalAppts++; totalRevenue += grand;
    }
  }
}

S('');
S('-- appointment line items');
itemLines.forEach(S);
S('');
S('-- stock consumed by completed services');
stockLines.forEach(S);
S('');

/* ---- monthly restocks and recurring costs, so profit is not fictional --- */
S('-- recurring costs for the historical months');
let expNo = 0;
[['2026-06', 'June'], ['2026-07', 'July']].forEach(([ym, label]) => {
  const rows = [
    ['rent', `Shop rent — ${label}`, 150000, 'cash', `${ym}-05`],
    ['utilities', `ENEO electricity — ${label}`, 38000 + Math.floor(rnd() * 8000), 'cash', `${ym}-15`],
    ['utilities', `Water + internet — ${label}`, 25000, 'momo', `${ym}-15`],
    ['salaries', `Staff commissions — ${label}`, 380000 + Math.floor(rnd() * 60000), 'momo', `${ym}-28`],
    ['restock', `Product restock — ${label}`, 90000 + Math.floor(rnd() * 40000), 'momo', `${ym}-08`],
    ['marketing', `Social ads — ${label}`, 25000, 'card', `${ym}-03`],
  ];
  rows.forEach(([cat, desc, amt, pay, on]) =>
    S(`INSERT INTO expenses (ref, category_id, description, amount, payment_method, spent_on, is_recurring) VALUES ` +
      `(${q('EXH-' + String(++expNo).padStart(3, '0'))}, (SELECT id FROM expense_categories WHERE slug = ${q(cat)}), ` +
      `${q(desc)}, ${amt}, ${q(pay)}, ${q(on)}, ${['rent', 'utilities', 'salaries'].includes(cat) ? 1 : 0});`));
});
S('');

/* Restocks, so the stock ledger nets out sensibly rather than going deeply
   negative after ten weeks of consumption. */
S('-- restocks offsetting historical consumption');
const used = {};
stockLines.forEach(l => { const m = l.match(/ref = '(P-\d+)'/); if (m) used[m[1]] = (used[m[1]] || 0) + 1; });
Object.entries(used).forEach(([p, n]) => {
  const qty = Math.ceil(n * 1.1);
  S(`INSERT INTO stock_movements (ref, product_id, movement_type, qty, reference, note, moved_on) VALUES ` +
    `(${q('SHR-' + p)}, (SELECT id FROM products WHERE ref = ${q(p)}), 'in', ${qty}, 'PO-HIST', ` +
    `'Historical restock', '2026-06-01');`);
});
S('');

const target = path.join(ROOT, 'db/migrations/0003_history.sql');
fs.writeFileSync(target, out.join('\n') + '\n', 'utf8');
console.log(`Wrote ${path.relative(ROOT, target)}`);
console.log(`  ${apptNo} appointments (${totalAppts} completed), ` +
  `${totalRevenue.toLocaleString('en-US')} FCFA of completed revenue across 10 weeks`);
console.log(`  ${stockLines.length} stock movements, ${expNo} historical expenses`);
