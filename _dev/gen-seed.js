/**
 * Generates db/migrations/0002_seed.sql directly from _dev/seed-data.js.
 *
 * The prototype's mock data IS the seed data — transcribing 33 appointments,
 * 24 services and 18 products by hand would introduce errors that are tedious
 * to find later. Generating guarantees the database matches the UI the owner
 * signed off on.
 *
 *   node _dev/gen-seed.js
 *
 * Re-run this whenever data.js changes, then `php db/migrate.php --fresh`.
 * Foreign keys are resolved by `ref`/`slug` subquery rather than by assuming
 * auto-increment values, so the file is order-independent and re-runnable.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

/* data.js is a browser IIFE that hangs everything off `window`. */
global.window = {};
require(path.join(ROOT, '_dev/seed-data.js'));
const PBS = global.window.PBS;
if (!PBS) { console.error('Could not load PBS from data.js'); process.exit(1); }

/* ----------------------------------------------------------------- helpers */
const q = v => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";
};
const catId    = slug => `(SELECT id FROM service_categories WHERE slug = ${q(slug)})`;
const staffId  = ref  => ref ? `(SELECT id FROM staff WHERE ref = ${q(ref)})` : 'NULL';
const svcId    = ref  => `(SELECT id FROM services WHERE ref = ${q(ref)})`;
const prodId   = ref  => `(SELECT id FROM products WHERE ref = ${q(ref)})`;
const clientId = ref  => `(SELECT id FROM clients WHERE ref = ${q(ref)})`;
const roleId   = slug => `(SELECT id FROM roles WHERE slug = ${q(slug)})`;
const apptId   = ref  => `(SELECT id FROM appointments WHERE ref = ${q(ref)})`;
const userId   = ref  => `(SELECT id FROM users WHERE ref = ${q(ref)})`;
const expCatId = slug => `(SELECT id FROM expense_categories WHERE slug = ${q(slug)})`;

const addMinutes = (hhmm, mins) => {
  const [h, m] = hhmm.split(':').map(Number);
  const t = h * 60 + m + mins;
  return String(Math.floor(t / 60) % 24).padStart(2, '0') + ':' + String(t % 60).padStart(2, '0') + ':00';
};

const out = [];
const S = s => out.push(s);

S('-- =============================================================================');
S('-- Princess Beauty Salon — seed data');
S('-- GENERATED by _dev/gen-seed.js from _dev/seed-data.js. Do not edit by hand;');
S('-- edit data.js and regenerate, or the UI and the database will disagree.');
S('-- =============================================================================');
S('');
S('SET NAMES utf8mb4;');
S('');

/* ------------------------------------------------------------------ settings */
S('-- ------------------------------------------------------------ settings');
const salon = PBS.salon;
const settings = {
  salon_name: salon.name, tagline: salon.tagline, phone: salon.phone,
  whatsapp: salon.whatsapp, email: salon.email, address: salon.address,
  currency: salon.currency, currency_code: salon.currencyCode,
  tax_rate: String(salon.taxRate),
  instagram: salon.socials.instagram, tiktok: salon.socials.tiktok,
  facebook: salon.socials.facebook,
  booking_window_days: '21', min_notice_hours: '2', slot_interval_minutes: '30',
  buffer_minutes: '10', free_cancel_hours: '4',
  deposit_threshold: '20000', deposit_percent: '30',
  default_commission_pct: '35', commission_basis: 'service_only',
  brand_black: '#0B0B0B', brand_gold: '#C9A227', brand_pink: '#E91E8C',
};
Object.entries(settings).forEach(([k, v]) =>
  S(`INSERT INTO settings (\`key\`, \`value\`) VALUES (${q(k)}, ${q(v)}) ON DUPLICATE KEY UPDATE \`value\` = VALUES(\`value\`);`));
S('');

/* ------------------------------------------------------------ business hours */
S('-- -------------------------------------------------------- business hours');
PBS.salon.hours.forEach((h, i) =>
  S(`INSERT INTO business_hours (weekday, day_name, opens_at, closes_at, is_closed) VALUES ` +
    `(${i}, ${q(h.day)}, ${q(h.open + ':00')}, ${q(h.close + ':00')}, ${h.closed ? 1 : 0});`));
S('');

/* --------------------------------------------------------- roles & permissions */
S('-- ----------------------------------------------------- roles & permissions');
PBS.roles.forEach(r =>
  S(`INSERT INTO roles (slug, name, description, is_system) VALUES (${q(r.id)}, ${q(r.name)}, ${q(r.desc)}, 1);`));
S('');

const AREAS = [
  ['dashboard', 'View dashboard', 'overview'],
  ['appointments', 'Manage appointments', 'operations'],
  ['clients', 'Manage clients', 'operations'],
  ['services', 'Manage services', 'operations'],
  ['staff', 'Manage staff', 'operations'],
  ['revenue', 'View revenue & reports', 'business'],
  ['expenses', 'Manage expenses', 'business'],
  ['inventory', 'Manage inventory & POS', 'business'],
  ['users', 'Manage user accounts', 'administration'],
  ['settings', 'Change settings', 'administration'],
  ['my-schedule', 'View own schedule', 'personal'],
  ['my-clients', 'View own clients', 'personal'],
  ['my-performance', 'View own performance', 'personal'],
];
AREAS.forEach(([slug, name, area]) =>
  S(`INSERT INTO permissions (slug, name, area) VALUES (${q(slug)}, ${q(name)}, ${q(area)});`));
S('');
PBS.roles.forEach(r => {
  /* the owner implicitly has every area, including the personal ones */
  const perms = r.id === 'owner' ? AREAS.map(a => a[0]) : r.perms;
  perms.forEach(p =>
    S(`INSERT INTO role_permissions (role_id, permission_id) VALUES ` +
      `(${roleId(r.id)}, (SELECT id FROM permissions WHERE slug = ${q(p)}));`));
});
S('');

/* -------------------------------------------------------- service categories */
S('-- ------------------------------------------------------ service categories');
PBS.categories.forEach((c, i) =>
  S(`INSERT INTO service_categories (slug, name, short_name, icon, color, blurb, sort_order) VALUES ` +
    `(${q(c.id)}, ${q(c.name)}, ${q(c.short)}, ${q(c.icon)}, ${q(c.color)}, ${q(c.blurb)}, ${i});`));
S('');

/* ------------------------------------------------------------------- staff */
S('-- --------------------------------------------------------------- staff');
PBS.staff.forEach((s, i) =>
  S(`INSERT INTO staff (ref, name, job_title, bio, commission_pct, rating, reviews_count, working_hours, since_year, tone, is_public, sort_order) VALUES ` +
    `(${q(s.id)}, ${q(s.name)}, ${q(s.role)}, ${q(s.bio)}, ${s.commission}, ${s.rating}, ${s.reviews}, ` +
    `${q(s.hours)}, ${q(s.since)}, ${q(s.tone)}, 1, ${i});`));
S('');
PBS.staff.forEach(s => s.cats.forEach(c =>
  S(`INSERT INTO staff_categories (staff_id, category_id) VALUES (${staffId(s.id)}, ${catId(c)});`)));
S('');

/* Weekly rota — mirrors the grid shown on admin/staff.html (0 = Monday). */
S('-- rota: 0 = Monday .. 6 = Sunday; a missing row means "not working"');
const ROTA = {
  'ST-01': [1, 1, 1, 1, 1, 1, 0], 'ST-02': [1, 1, 1, 1, 1, 1, 0],
  'ST-03': [0, 1, 1, 1, 1, 1, 1], 'ST-04': [1, 1, 1, 1, 1, 0, 0],
  'ST-05': [0, 0, 1, 1, 1, 1, 1], 'ST-06': [1, 1, 1, 1, 1, 1, 0],
};
PBS.staff.forEach(s => {
  const m = (s.hours.split('·')[1] || '09:00 - 19:00').trim().split('-');
  const from = (m[0] || '09:00').trim() + ':00';
  const to   = (m[1] || '19:00').trim() + ':00';
  (ROTA[s.id] || []).forEach((on, wd) => {
    if (on) S(`INSERT INTO staff_hours (staff_id, weekday, starts_at, ends_at) VALUES (${staffId(s.id)}, ${wd}, ${q(from)}, ${q(to)});`);
  });
});
S('');

/* ------------------------------------------------------------------- users */
S('-- --------------------------------------------------------------- users');
S('-- password for every seeded account is: demo1234');
const DEMO_HASH = '$2y$12$DaJwq5kB9d2F0Et9spL74up2Zz6wka7mt/ZVl27iXpbH1VA0x6xfC';
PBS.users.forEach(u =>
  S(`INSERT INTO users (ref, staff_id, role_id, name, email, password_hash, status, two_factor, last_login_at) VALUES ` +
    `(${q(u.id)}, ${staffId(u.staffId)}, ${roleId(u.role)}, ${q(u.name)}, ${q(u.email)}, ` +
    `${u.status === 'invited' ? 'NULL' : q(DEMO_HASH)}, ${q(u.status)}, ${u.twoFA ? 1 : 0}, ` +
    `${u.lastLogin === '—' ? 'NULL' : q(u.lastLogin + ':00')});`));
S('');

/* ---------------------------------------------------------------- products */
S('-- ------------------------------------------------------------ products');
PBS.products.forEach(p =>
  S(`INSERT INTO products (ref, name, category_id, unit, qty_on_hand, reorder_level, unit_cost, retail_price, is_retail, supplier) VALUES ` +
    `(${q(p.id)}, ${q(p.name)}, ${p.cat === 'general' ? 'NULL' : catId(p.cat)}, ${q(p.unit)}, ` +
    `${p.qty}, ${p.reorder}, ${p.cost}, ${p.sell}, ${p.retail ? 1 : 0}, ${q(p.supplier)});`));
S('');

/* ---------------------------------------------------------------- services */
S('-- ------------------------------------------------------------ services');
PBS.services.forEach((s, i) =>
  S(`INSERT INTO services (ref, category_id, name, description, price, duration_minutes, is_popular, is_public, sort_order) VALUES ` +
    `(${q(s.id)}, ${catId(s.cat)}, ${q(s.name)}, ${q(s.desc)}, ${s.price}, ${s.duration}, ${s.popular ? 1 : 0}, 1, ${i});`));
S('');
PBS.services.forEach(s => (s.uses || []).forEach(p =>
  S(`INSERT INTO service_products (service_id, product_id, qty_used) VALUES (${svcId(s.id)}, ${prodId(p)}, 1);`)));
S('');

/* ----------------------------------------------------------------- clients */
S('-- ------------------------------------------------------------- clients');
PBS.clients.forEach(c =>
  S(`INSERT INTO clients (ref, name, phone, email, notes, fav_category_id, fav_staff_id, joined_on, marketing_opt_in) VALUES ` +
    `(${q(c.id)}, ${q(c.name)}, ${q(c.phone)}, ${q(c.email)}, ${q(c.notes || null)}, ` +
    `${catId(c.fav)}, ${staffId(c.favStaff)}, ${q(c.joined)}, 1);`));
S('');

/* ------------------------------------------------------------ appointments */
S('-- --------------------------------------------------------- appointments');
PBS.appointments.forEach(a => {
  const svcs = a.svc.map(id => PBS.service(id)).filter(Boolean);
  const dur  = svcs.reduce((t, s) => t + s.duration, 0);
  const svcTotal = svcs.reduce((t, s) => t + s.price, 0);
  const grand = svcTotal + (a.addons || 0) + (a.tip || 0);
  const paid = a.pay !== 'unpaid' ? q(a.date + ' ' + a.time + ':00') : 'NULL';
  S(`INSERT INTO appointments (ref, client_id, staff_id, booked_on, starts_at, ends_at, duration_minutes, status, payment_method, paid_at, services_total, addons_total, tip_total, grand_total, note, source) VALUES ` +
    `(${q(a.id)}, ${clientId(a.client)}, ${staffId(a.staff)}, ${q(a.date)}, ${q(a.time + ':00')}, ` +
    `${q(addMinutes(a.time, dur))}, ${dur}, ${q(a.status)}, ${q(a.pay)}, ${paid}, ` +
    `${svcTotal}, ${a.addons || 0}, ${a.tip || 0}, ${grand}, ${q(a.note || null)}, 'online');`);
  svcs.forEach(s =>
    S(`INSERT INTO appointment_items (appointment_id, service_id, service_name, unit_price, duration_minutes, qty, line_total) VALUES ` +
      `(${apptId(a.id)}, ${svcId(s.id)}, ${q(s.name)}, ${s.price}, ${s.duration}, 1, ${s.price});`));
});
S('');

/* ----------------------------------------------------------- retail sales */
S('-- ---------------------------------------------------------- retail sales');
PBS.productSales.forEach(s => {
  const p = PBS.productById(s.product);
  const total = s.qty * s.unitPrice;
  S(`INSERT INTO product_sales (ref, client_id, sold_by, sold_on, payment_method, total) VALUES ` +
    `(${q(s.id)}, ${clientId(s.client)}, ${staffId(s.by)}, ${q(s.date)}, ${q(s.pay)}, ${total});`);
  S(`INSERT INTO product_sale_items (sale_id, product_id, product_name, unit_price, qty, line_total) VALUES ` +
    `((SELECT id FROM product_sales WHERE ref = ${q(s.id)}), ${prodId(s.product)}, ${q(p.name)}, ${s.unitPrice}, ${s.qty}, ${total});`);
});
S('');

/* -------------------------------------------------------- stock movements */
S('-- ------------------------------------------------------- stock movements');
S('-- qty is signed: "in" adds, everything else removes');
PBS.stockLog.forEach(m => {
  const signed = m.type === 'in' ? Math.abs(m.qty) : (m.qty < 0 ? m.qty : -Math.abs(m.qty));
  S(`INSERT INTO stock_movements (ref, product_id, movement_type, qty, reference, note, staff_id, moved_on) VALUES ` +
    `(${q(m.id)}, ${prodId(m.product)}, ${q(m.type)}, ${signed}, ${q(m.ref === '—' ? null : m.ref)}, ` +
    `${q(m.note)}, ${staffId(m.by)}, ${q(m.date)});`);
});
S('');

/* ---------------------------------------------------------------- expenses */
S('-- ------------------------------------------------------------ expenses');
const EXP_CATS = [
  ['rent', 'Rent', '#E91E8C', 1], ['restock', 'Product restock', '#C9A227', 0],
  ['salaries', 'Salaries & commissions', '#0B0B0B', 1], ['utilities', 'Utilities', '#2F6FED', 1],
  ['marketing', 'Marketing', '#12A150', 0], ['maintenance', 'Maintenance', '#A8A8B3', 0],
  ['other', 'Other', '#77777F', 0],
];
EXP_CATS.forEach(([slug, name, color, fixed]) =>
  S(`INSERT INTO expense_categories (slug, name, color, is_fixed) VALUES (${q(slug)}, ${q(name)}, ${q(color)}, ${fixed});`));
S('');
PBS.expenses.forEach(e =>
  S(`INSERT INTO expenses (ref, category_id, description, amount, payment_method, spent_on, recorded_by, is_recurring) VALUES ` +
    `(${q(e.id)}, ${expCatId(e.cat.toLowerCase())}, ${q(e.label)}, ${e.amount}, ${q(e.pay)}, ${q(e.date)}, ` +
    `${staffId(e.by)}, ${['Rent', 'Utilities', 'Salaries'].includes(e.cat) ? 1 : 0});`));
S('');

/* ------------------------------------------------------------------ offers */
S('-- -------------------------------------------------------------- offers');
PBS.offers.forEach((o, i) => {
  S(`INSERT INTO offers (ref, title, category_id, blurb, badge, price, was_price, valid_until, is_active, sort_order) VALUES ` +
    `(${q(o.id)}, ${q(o.title)}, ${catId(o.cat)}, ${q(o.blurb)}, ${q(o.badge)}, ${o.price}, ${o.was}, ${q(o.until)}, 1, ${i});`);
  o.includes.forEach((label, j) =>
    S(`INSERT INTO offer_items (offer_id, label, sort_order) VALUES ((SELECT id FROM offers WHERE ref = ${q(o.id)}), ${q(label)}, ${j});`));
});
S('');

/* The gallery is no longer seeded. Photos are files: whatever sits under
   assets/img/<folder>/ becomes a row when `npm run images` scans it, and the
   database stores only the folder and the filename. See 0006_gallery_folders. */

/* ----------------------------------------------------------------- reviews */
S('-- ------------------------------------------------------------- reviews');
PBS.testimonials.forEach(t =>
  S(`INSERT INTO reviews (client_name, service_label, stars, body, is_public) VALUES ` +
    `(${q(t.name)}, ${q(t.service)}, ${t.stars}, ${q(t.text)}, 1);`));
S('');

/* -------------------------------------------------------------------- FAQs */
S('-- ---------------------------------------------------------------- faqs');
PBS.faqs.forEach((f, i) =>
  S(`INSERT INTO faqs (category, question, answer, is_public, sort_order) VALUES ` +
    `(${q(f.cat)}, ${q(f.q)}, ${q(f.a)}, 1, ${i});`));
S('');

/* --------------------------------------------------------------- audit log */
S('-- ----------------------------------------------------------- audit log');
PBS.activity.forEach(a =>
  S(`INSERT INTO audit_log (user_id, action, entity_type, created_at) VALUES ` +
    `(${userId(a.user)}, ${q(a.action)}, ${q(a.type)}, ${q(a.time + ':00')});`));
S('');

const target = path.join(ROOT, 'db/migrations/0002_seed.sql');
fs.writeFileSync(target, out.join('\n') + '\n', 'utf8');

const stmts = out.filter(l => l.startsWith('INSERT')).length;
console.log(`Wrote ${path.relative(ROOT, target)} — ${stmts} INSERT statements, ${out.length} lines.`);
